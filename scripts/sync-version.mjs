// The version, written major.minor.build (for example 1.1.12). Makes frontend/src/environments/version.ts (generated, gitignored) from
// frontend/build-number.json (committed): { "major": 1, "minor": 1, "number": 12 }. Change major or minor by hand in that file; the build number
// goes up by one for every build.
//   node scripts/sync-version.mjs --bump   a build (npm run build, so every deploy): the build number goes up by one
//   node scripts/sync-version.mjs          a development server or a test: the number stays, the version is marked "dev"
// The version is shown in Settings > About and rules > About, so it is easy to see which build an app (Windows, Android, a browser) runs.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const counterFile = join(root, 'frontend', 'build-number.json');
const bump = process.argv.includes('--bump');

let counter = { major: 1, minor: 0, number: 0 };
if (existsSync(counterFile)) counter = { ...counter, ...JSON.parse(readFileSync(counterFile, 'utf8')) };
const major = Number(counter.major) || 0;
const minor = Number(counter.minor) || 0;
let number = Number(counter.number) || 0;
if (bump) {
  number += 1;
  writeFileSync(counterFile, JSON.stringify({ major, minor, number }, null, 2) + '\n');
}

const out = join(root, 'frontend', 'src', 'environments', 'version.ts');
mkdirSync(dirname(out), { recursive: true });
writeFileSync(
  out,
  `// GENERATED by scripts/sync-version.mjs from frontend/build-number.json. Do not edit, do not commit.
export const version = {
  /** the version as it is shown: major.minor.build */
  name: '${major}.${minor}.${number}',
  major: ${major},
  minor: ${minor},
  /** the build number: one more for every build (every deploy) */
  number: ${number},
  /** the time of this build or start, as an ISO time */
  builtAt: '${new Date().toISOString()}',
  /** true = a development server, not a build for the people */
  dev: ${!bump},
};
`,
);
console.log(`sync-version: ${bump ? 'build' : 'dev'} ${major}.${minor}.${number}`);
