#!/usr/bin/env node
/**
 * Copies the shared models into the frontend, so the backend and the frontend use the same
 * model files without sharing a module:
 *
 *   functions/src/models/shared/*.ts   (the ONE place to edit)
 *        ->  frontend/src/app/models/shared/*.ts   (generated copy, not committed)
 *
 * It runs by itself before every frontend start / build (npm pre-hooks), and by hand with:
 *   npm run sync:models
 *
 * Options:
 *   --check        change nothing, exit 1 if the frontend copy is missing or out of date
 *   --to <dir>     copy to another folder (used by the tests)
 *   --from <dir>   read from another folder (used by the tests)
 *
 * The shared folder holds TYPES and plain DATA (constants and small pure functions, e.g. the languages), and may only
 * import from itself ("./"), because the frontend has none of the backend's packages.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const args = process.argv.slice(2);
const option = (name) => (args.includes(name) ? path.resolve(args[args.indexOf(name) + 1] ?? "") : undefined);

const source = option("--from") ?? path.join(root, "functions", "src", "models", "shared");
const target = option("--to") ?? path.join(root, "frontend", "src", "app", "models", "shared");
const checkOnly = args.includes("--check");

const HEADER =
  "// GENERATED by scripts/sync-models.mjs from functions/src/models/shared.\n" +
  "// Do not edit here: change the source file, then run `npm run sync:models`\n" +
  "// (it also runs before every frontend start and build).\n\n";

function fail(message) {
  console.error(`sync-models: ${message}`);
  process.exit(1);
}

if (!fs.existsSync(source)) fail(`source folder not found: ${source}`);
const files = fs.readdirSync(source).filter((f) => f.endsWith(".ts")).sort();
if (!files.length) fail(`no .ts files in ${source}`);

// 1. imports only from the folder itself (types and plain data are fine)
const problems = [];
for (const file of files) {
  const text = fs.readFileSync(path.join(source, file), "utf8");
  for (const m of text.matchAll(/^\s*(?:import|export)\b[^;]*?\bfrom\s+["']([^"']+)["']/gm)) {
    if (!m[1].startsWith("./")) problems.push(`${file}: imports "${m[1]}" (shared models may only import from "./")`);
  }
}
if (problems.length) fail(`the shared models are not shareable:\n  - ${problems.join("\n  - ")}`);

// 2. what the copy should look like
const wanted = new Map(files.map((f) => [f, HEADER + fs.readFileSync(path.join(source, f), "utf8")]));
const stale = fs.existsSync(target)
  ? fs
      .readdirSync(target)
      .filter((f) => f.endsWith(".ts") && !wanted.has(f))
      .filter((f) => fs.readFileSync(path.join(target, f), "utf8").startsWith("// GENERATED")) // never touch hand-written files
  : [];

const changed = [...wanted].filter(([f, text]) => {
  const file = path.join(target, f);
  return !fs.existsSync(file) || fs.readFileSync(file, "utf8") !== text;
});

if (checkOnly) {
  const out = [...changed.map(([f]) => `out of date: ${f}`), ...stale.map((f) => `should not exist: ${f}`)];
  if (out.length) fail(`${target} is not in sync:\n  - ${out.join("\n  - ")}\n  run: npm run sync:models`);
  console.log(`sync-models: ${files.length} model files are in sync`);
  process.exit(0);
}

// 3. write only what changed (so a running dev server is not restarted for nothing)
fs.mkdirSync(target, { recursive: true });
for (const [f, text] of changed) fs.writeFileSync(path.join(target, f), text);
for (const f of stale) fs.unlinkSync(path.join(target, f));
console.log(
  `sync-models: ${files.length} model files -> ${path.relative(root, target) || target} ` +
    `(${changed.length} updated, ${files.length - changed.length} unchanged${stale.length ? `, ${stale.length} removed` : ""})`,
);
