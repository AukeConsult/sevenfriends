// Makes frontend/src/environments/features.ts (generated, gitignored) from PHONE_AUTH in .env (or in the environment of the command).
//   PHONE_AUTH=on   phone sign-in and phone verification (SMS) are shown
//   PHONE_AUTH=off  (or not set) they are hidden and their routes do not exist: no SMS can be sent from the app
// Runs before every frontend start / build / test (npm pre-hooks), so a change in .env needs a restart of `npm run dev:frontend` or a new build.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const envFile = join(root, '.env');

/** the value of one key in .env (the last one wins; quotes are removed), or undefined */
function fromEnvFile(key) {
  if (!existsSync(envFile)) return undefined;
  let value;
  for (const line of readFileSync(envFile, 'utf8').split(/\r?\n/)) {
    const m = line.match(new RegExp(`^\\s*${key}\\s*=\\s*(.*?)\\s*$`));
    if (m) value = m[1].replace(/^(['"])(.*)\1$/, '$2');
  }
  return value;
}

const raw = (process.env.PHONE_AUTH ?? fromEnvFile('PHONE_AUTH') ?? 'off').trim().toLowerCase();
const phoneAuth = ['on', 'true', '1', 'yes'].includes(raw);

const out = join(root, 'frontend', 'src', 'environments', 'features.ts');
mkdirSync(dirname(out), { recursive: true });
const text = `// GENERATED by scripts/sync-features.mjs from PHONE_AUTH in .env. Do not edit, do not commit.
export const features = {
  /** SMS: phone sign-in (/login/phone) and verifying a phone (/verify-phone) */
  phoneAuth: ${phoneAuth},
} as const;
`;
if (!existsSync(out) || readFileSync(out, 'utf8') !== text) writeFileSync(out, text);
console.log(`features: phone authentication is ${phoneAuth ? 'ON' : 'OFF'} (PHONE_AUTH=${raw})`);
