import { spawnSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { afterEach, beforeEach, describe, expect, it } from "vitest";

/**
 * The shared models (functions/src/models/shared) are copied into the frontend by
 * scripts/sync-models.mjs. These tests make sure the copy works and the shared folder stays shareable.
 */
const root = path.resolve(__dirname, "../..");
const script = path.join(root, "scripts", "sync-models.mjs");
const shared = path.join(root, "functions", "src", "models", "shared");

const run = (...args: string[]) => {
  const result = spawnSync(process.execPath, [script, ...args], { encoding: "utf8" });
  return { code: result.status, out: `${result.stdout}${result.stderr}` };
};

let tmp: string;
beforeEach(() => { tmp = fs.mkdtempSync(path.join(os.tmpdir(), "sf-models-")); });
afterEach(() => { fs.rmSync(tmp, { recursive: true, force: true }); });

const sourceFiles = () => fs.readdirSync(shared).filter((f) => f.endsWith(".ts"));

describe("the shared models folder", () => {
  it("holds only types, and imports only from itself (so the frontend can compile a copy)", () => {
    expect(sourceFiles().length).toBeGreaterThan(3);
    const result = run("--to", path.join(tmp, "copy"));
    expect(result.code, result.out).toBe(0);
  });

  it("is copied file by file, with a 'generated' header", () => {
    const to = path.join(tmp, "copy");
    expect(run("--to", to).code).toBe(0);
    expect(fs.readdirSync(to).sort()).toEqual(sourceFiles().sort());
    for (const f of sourceFiles()) {
      const copy = fs.readFileSync(path.join(to, f), "utf8");
      expect(copy.startsWith("// GENERATED by scripts/sync-models.mjs")).toBe(true);
      expect(copy.endsWith(fs.readFileSync(path.join(shared, f), "utf8"))).toBe(true);
    }
  });

  it("only rewrites what changed, and --check notices a stale or missing copy", () => {
    const to = path.join(tmp, "copy");
    expect(run("--check", "--to", to).code).toBe(1); // nothing copied yet
    run("--to", to);
    expect(run("--check", "--to", to).code).toBe(0);
    expect(run("--to", to).out).toMatch(/0 updated/);

    fs.appendFileSync(path.join(to, "friend.ts"), "\n// edited by hand\n");
    const stale = run("--check", "--to", to);
    expect(stale.code).toBe(1);
    expect(stale.out).toMatch(/out of date: friend\.ts/);
    expect(run("--to", to).out).toMatch(/1 updated/);
    expect(run("--check", "--to", to).code).toBe(0);
  });

  it("removes generated files whose source is gone, but never hand-written ones", () => {
    const to = path.join(tmp, "copy");
    run("--to", to);
    fs.writeFileSync(path.join(to, "old.ts"), "// GENERATED earlier\nexport type Old = string;\n");
    fs.writeFileSync(path.join(to, "mine.ts"), "export type Mine = string; // written by hand\n");
    expect(run("--to", to).out).toMatch(/1 removed/);
    expect(fs.existsSync(path.join(to, "old.ts"))).toBe(false);
    expect(fs.existsSync(path.join(to, "mine.ts"))).toBe(true);
  });

  it.each([
    ["an import from a package", 'import { Timestamp } from "firebase-admin/firestore";\nexport type T = Timestamp;\n', /imports "firebase-admin\/firestore"/],
    ["an import from outside the folder", 'import { X } from "../constants";\nexport type T = X;\n', /imports "\.\.\/constants"/],
  ])("refuses %s in a shared model", (_label, content, message) => {
    const from = path.join(tmp, "src");
    fs.mkdirSync(from);
    fs.writeFileSync(path.join(from, "bad.ts"), content);
    const result = run("--from", from, "--to", path.join(tmp, "copy"));
    expect(result.code).toBe(1);
    expect(result.out).toMatch(message);
    expect(fs.existsSync(path.join(tmp, "copy"))).toBe(false); // nothing was copied
  });

  it("allows plain data and small functions (the languages)", () => {
    const from = path.join(tmp, "src");
    fs.mkdirSync(from);
    fs.writeFileSync(path.join(from, "data.ts"), 'export const LIMIT = 7;\nexport function twice(n: number) { return n * 2; }\n');
    expect(run("--from", from, "--to", path.join(tmp, "copy")).code).toBe(0);
  });

  it("allows type-only files that import each other", () => {
    const from = path.join(tmp, "src");
    fs.mkdirSync(from);
    fs.writeFileSync(path.join(from, "a.ts"), "export type A = string;\n");
    fs.writeFileSync(path.join(from, "b.ts"), 'import { A } from "./a";\nexport interface B { a: A }\n');
    expect(run("--from", from, "--to", path.join(tmp, "copy")).code).toBe(0);
  });
});
