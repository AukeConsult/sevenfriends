/** The language a country gets without a choice. */
export function defaultLanguage(country: string | null): string {
  return (country && COUNTRY_LANGUAGES[country]?.[0]) || 'en';
}

/** What to choose from for a country: its own languages first, then English, French and Spanish. */
export function languagesFor(country: string | null): { code: string; name: string }[] {
  const own = (country && COUNTRY_LANGUAGES[country]) || [];
  return [...new Set([...own, 'en', 'fr', 'es'])].map((code) => ({ code, name: LANGUAGE_NAMES[code] }));
}

/** All the language codes. */
export const LANGUAGES = Object.keys(LANGUAGE_NAMES);

export function isLanguage(code: unknown): code is string {
  return typeof code === 'string' && LANGUAGES.includes(code);
}
